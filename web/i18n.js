const I18N = (() => {
  const STORAGE_KEY = 'rtg.lang';
  const DEFAULT_LANG = 'en';
  const SUPPORTED = ['en', 'zh-CN'];
  let current = DEFAULT_LANG;

  function normalize(value) {
    return SUPPORTED.indexOf(value) === -1 ? null : value;
  }

  function stored() {
    try {
      return normalize(window.localStorage.getItem(STORAGE_KEY));
    } catch (error) {
      return null;  // private mode / blocked storage: fall back to the browser language
    }
  }

  function initial() {
    const saved = stored();
    if (saved) return saved;  // an explicit choice always wins
    const nav = String(navigator.language || '').toLowerCase();
    return nav.indexOf('zh') === 0 ? 'zh-CN' : DEFAULT_LANG;
  }

  function t(key, params) {
    const table = I18N_MESSAGES[current] || I18N_MESSAGES[DEFAULT_LANG];
    let text = table[key];
    if (text === undefined) text = I18N_MESSAGES[DEFAULT_LANG][key];
    if (text === undefined) return key;  // a missing key must be visible, never silent
    return String(text).replace(/\{(\w+)\}/g, (match, name) =>
      params && params[name] !== undefined ? String(params[name]) : match
    );
  }

  function apply(root) {
    const scope = root || document;
    scope.querySelectorAll('[data-i18n]').forEach((node) => {
      node.textContent = t(node.dataset.i18n);
    });
    scope.querySelectorAll('[data-i18n-placeholder]').forEach((node) => {
      node.setAttribute('placeholder', t(node.dataset.i18nPlaceholder));
    });
    scope.querySelectorAll('[data-i18n-aria]').forEach((node) => {
      node.setAttribute('aria-label', t(node.dataset.i18nAria));
    });
  }

  function sync() {
    document.documentElement.setAttribute('lang', current);
    const select = document.getElementById('lang-switch');
    if (select) select.value = current;
    apply(document);
  }

  function set(lang) {
    const next = normalize(lang) || DEFAULT_LANG;
    // Re-applying the same language would overwrite text the script owns
    // (gateway status, rendered results) for no benefit.
    if (next === current) return current;
    current = next;
    try {
      window.localStorage.setItem(STORAGE_KEY, next);
    } catch (error) {
      /* storage unavailable: the switch still works for this page */
    }
    sync();
    document.dispatchEvent(new CustomEvent('rtg:langchange', { detail: { lang: next } }));
    return current;
  }

  function init() {
    current = initial();
    sync();
    const select = document.getElementById('lang-switch');
    if (select) {
      select.addEventListener('change', (event) => set(event.target.value));
    }
    return current;
  }

  return {
    STORAGE_KEY,
    SUPPORTED,
    init,
    set,
    t,
    apply,
    get lang() {
      return current;
    },
  };
})();
